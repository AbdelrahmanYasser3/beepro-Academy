export const getLearningCategory = (categoryKey) =>
  learningCategories.find(
    (category) => category.id === categoryKey || category.slug === categoryKey,
  );

export const getStaticCourse = (slug, categorySlug) =>
  learningCategories
    .filter((category) => !categorySlug || category.slug === categorySlug)
    .flatMap((category) => category.courses)
    .find((course) => course.slug === slug);
