const createCourses = (categoryId, image, rows) =>
  rows.map(
    ([slug, title, titleAr, description, descriptionAr, level, duration, lessonsCount, tags, tagsAr], index) => ({
      id: `${categoryId}-demo-${index + 1}`,
      slug,
      title,
      titleAr,
      description,
      descriptionAr,
      instructor: demoInstructor,
      level,
      duration,
      lessonsCount,
      image: Array.isArray(image)
        ? image[index]
        : typeof image === 'string' && image.startsWith('/')
          ? image
          : `https://picsum.photos/seed/${slug}/400/200`,
      tags,
      tagsAr,
      featured: index < 2,
      isDemo: true,
    }),
  );

